const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

export function buildSeedProducts(): Product[] {
  const out: Product[] = [];
  for (const cat of categories) {
    for (const r of rows[cat.slug]) {
      const brand = brands.find((b) => b.slug === r.brand)!;
      const specs: Spec[] = r.specs.map(([label, value]) => ({ label, value }));
      specs.push({ label: "Warranty", value: "12 months parts & labour" });
      out.push({
        slug: slugify(`${r.name} ${r.model}`),
        name: r.name,
        model: r.model,
        category: cat.slug,
        brand: r.brand,
        summary: r.summary,
        description: `${r.summary} Built by ${brand.name} (${brand.origin}) for the demands of commercial foodservice, the ${r.model} is supplied with installation guidance, operator training and after-sales support from our service team. Speak to sales for site-specific configuration, gas/electrical requirements and delivery timelines.`,
        features: r.features,
        specs,
        art: r.art,
        images: [],
        brochure: null,
        featured: !!r.featured,
        isNew: !!r.isNew,
        leadTime: r.lead ?? "Ex-stock / 7–10 days",
        updatedAt: "2026-10-01T00:00:00.000Z",
      });
    }
  }
  return out;
}
